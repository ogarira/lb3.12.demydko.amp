#include <iostream> // бібліотека для введення та виведення даних (cin, cout)
#include <cmath>    // бібліотека для математичних функцій (pow, sin, cos, abs)

using namespace std; // використання стандартного простору імен

double y_math(double x = 1.0); // прототип функції 1 зі значенням x за замовчуванням
double task2();                // прототип функції 2 (Завдання 2)
double func(int n);            // прототип функції-розподільника

int main() {
    int N;    // змінна для збереження введеного цілого числа N
    double y; // змінна для збереження підрахованого результату

    cout << "Vvedit tsile chyslo N: "; // виведення підказки для користувача
    cin >> N;                          // зчитування значення N з клавіатури

    y = func(N); // викликаємо функцію-розподільник та передаємо їй N

    cout << "Otrymano rezultat y(" << N << ") = " << y << endl; // виведення кінцевого результату

    return 0; // завершення виконання програми без помилок
}

double y_math(double x) { // реалізація функції для обчислення математичного виразу
    double term1 = pow(sin(x), 2) / (pow(x, 2) - 4.0);                  // обчислення першого доданка: sin^2(x) / (x^2 - 4)
    double term2 = cos(pow(x, 2)) / (pow(x - 3.0, 13) * abs(x - 5.0)); // обчислення другого доданка: cos(x^2) / ((x-3)^13 * |x-5|)

    return term1 + term2; // повернення суми двох доданків
}

double task2() { // реалізація функції Завдання 2
    int num;             // змінна для чергового введеного числа
    int even_count = 0;  // лічильник парних чисел
    int odd_count = 0;   // лічильник непарних чисел
    int total_count = 0; // лічильник загальної кількості чисел
    double sum = 0;      // змінна для збереження суми чисел

    cout << "Vvedit tsili chysla (0 - zakinchennya vvodu):\n"; // підказка про введення
    cin >> num;                                              // зчитування першого числа

    while (num != 0) { // цикл працює, поки користувач не введе 0
        if (num % 2 == 0) { // перевірка, чи є число парним
            even_count++;   // збільшуємо лічильник парних чисел
        }
        else {
            odd_count++;    // збільшуємо лічильник непарних чисел
        }

        sum += num;    // додаємо число до загальної суми
        total_count++; // збільшуємо кількість введених чисел

        cin >> num; // зчитуємо наступне число
    }

    cout << "\nKilkist parnykh chysel: " << even_count << endl; // виведення кількості парних
    cout << "Kilkist neparnykh chysel: " << odd_count << endl;   // виведення кількості непарних

    if (total_count > 0) {
        return sum / total_count; // повертаємо середнє арифметичне (сума / кількість)
    }
    else {
        return 0; // якщо нічого не ввели, повертаємо 0
    }
}

double func(int n) { // реалізація головної функції
    if (n % 15 < 8) {  // перевірка умови: чи остача від ділення n на 15 менша за 8
        return y_math(); // викликаємо y_math() з параметром за замовчуванням (1.0)
    }
    else {
        return task2();  // викликаємо task2() для введення послідовності
    }
}